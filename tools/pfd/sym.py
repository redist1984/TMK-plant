def targets(t,p):
    """прямоугольники корпуса/штуцеров символа: концы труб и стрелок, не доходящие до них <=26 px, дотягиваются"""
    if t=='hx': return [[p['x0'],p['y0'],p['x1'],p['y1']]]
    if t=='boiler':
        dx0,dy0,dx1,dy1=p['dr'];xl,xb,xe,xc,y0,y1=p['sh']
        return [[dx0,dy0,dx1,dy1],[xl,y0,p['fl'][2],y1]]
    if t=='tower':
        xm,hw=p['xm'],p['hw'];r=[[xm-p['tn'],p['pr'][0][1]-9,xm+p['tn'],p['pr'][0][1]],[xm-p['bn'],p['db'],xm+p['bn'],p['db']+16]]
        for q in p.get('side',[]):
            y=q[0];ln=q[2] if len(q)>2 else 14;h=q[3] if len(q)>3 else 22
            r.append([xm+hw,y-h/2,xm+hw+ln,y+h/2] if q[1]=='r' else [xm-hw-ln,y-h/2,xm-hw,y+h/2])
        return r
    if t=='col':
        top=p['roof']['pl'][1] if p.get('roof') and p['roof'].get('pl') else (p['roof']['y'] if p.get('roof') else p['yt'])
        xr=p['base']['x1'] if p.get('base') else p['x1']
        return [[p['x0'],top,xr,p['base']['y1'] if p.get('base') else p['yb']]]
    if t=='vx':
        top=p['cone']['y'] if p.get('cone') else p['ys']-p['dome']
        return [[p['x0']-p['rd'],top,p['x1']+p['rd'],p['yb']]]
    if t=='re': return [list(p['b'])]
    if t=='fu': x0,y0,x1,y1=p['b']; return [[x0-22,y0-39,x1,y1]]
    if t=='hv':
        r=[[p['x0'],p['y0'],p['x1'],p['y1']]]
        if p.get('dome'): d=p['dome']; r.append([d['x0'],d['y0'],d['x1'],p['y0']])
        return r
    if t=='vv': return [[p['x0'],p['y0']-p['ry'],p['x1'],p['y1']+p['ry']]]
    if t=='tank': return [[p['x0'],p['y0'],p['x1'],p['y1']]]
    if t=='pump': return [[p['cx']-p['r'],p['cy']-p['r'],p['cx']+p['r'],p['cy']+p['r']]]
    if t=='sp': return [list(p['bowl'])]
    if t=='filter': return [[p['x0'],p['y0'],p['x1'],p['y1']]]
    if t=='dbox': return [[p['x0'],p['y0'],p['x1'],p['y1']]]
    return []
